/**
 * Converts English digits to Odia numerals
 */
export function toOdiaDigits(num: number | string, lang: Language): string {
  if (lang !== 'or') return String(num);
  const odiaDigits = ['୦', '୧', '୨', '୩', '୪', '୫', '୬', '୭', '୮', '୯'];
  return String(num).replace(/[0-9]/g, (d) => odiaDigits[parseInt(d, 10)]);
}
